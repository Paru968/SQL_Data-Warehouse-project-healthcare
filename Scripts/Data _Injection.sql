--------------------------------------------------------------------------------
-- 1. SILVER TABLE : ADMISSION
--
-- Business Purpose
-- Load admission records from Bronze to Silver after applying
-- data cleansing and standardization.
--
-- Transformations
-- • Convert date columns
-- • Remove leading/trailing spaces
-- • Populate DWH Create Date
--------------------------------------------------------------------------------

TRUNCATE TABLE silver.admission;
GO

INSERT INTO silver.admission
(
    admission_id,
    admission_date,
    discharge_date,
    admission_type,
    admission_status,
    patient_id,
    department_id,
    ward_id,
    bed_id,
    disease_id,
    batch_id,
    load_datetime,
    source_file_name,
    dwh_create_date
)

SELECT
    admission_id,
    CAST(admission_date AS DATE),
    CAST(discharge_date AS DATE),
    LTRIM(RTRIM(admission_type)),
    LTRIM(RTRIM(admission_status)),
    patient_id,
    department_id,
    ward_id,
    bed_id,
    disease_id,
    batch_id,
    load_datetime,
    source_file_name,
    GETDATE()

FROM bronze.admission;
GO

